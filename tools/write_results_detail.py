def ci(x):
    return "-" if not x else f"{x[0]}-{x[1]}"


def rc(r):
    """k/n = rate (95% CI)."""
    if r is None:
        return "trained on it"
    return f"{r['k']:,}/{r['n']:,} = {r['rate']} ({ci(r['ci95'])})"


def rate(r):
    return "-" if r is None else str(r["rate"])


